// 수강현황 게시글 제목을 어디서나 같은 이름으로 — 11/13 "메인 · 목록 · 상세에서 같은 글이 다른 이름으로 보인다"
// 메인 수강현황 · 수강현황 목록 · 수강현황 상세가 모두 이 함수를 쓴다.
// 앞머리로 반복되는 꼬리표만 덜어낸다(글 내용은 바꾸지 않음):
//   [금융멘토 문초록] 같은 대괄호 꼬리표 → 기관명 '국제명품감정교육원' → 브랜드 '진정성'
//   예) '국제명품감정교육원 명품감정 10기' → '명품감정 10기'
//       '[금융멘토 문초록] 진정성 명품감정 6기 강의' → '명품감정 6기 강의'
export const statusTitle = (title = '') => {
  const full = String(title).trim()
  const short = full
    .replace(/^(\[[^\]]*\]\s*)+/, '')
    .replace(/^국제명품감정교육원\s*/, '')
    .replace(/^진정성\s+/, '')
    .trim()
  return short || full
}
